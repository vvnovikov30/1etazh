import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import matter from "gray-matter";
import readingTime from "reading-time";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const BLOG_DIR = path.join(__dirname, "..", "content", "blog");
const OUTPUT_FILE = path.join(__dirname, "..", "lib", "blog.generated.ts");

function generateBlogIndex() {
  if (!fs.existsSync(BLOG_DIR)) {
    console.warn(`Warning: Blog directory ${BLOG_DIR} does not exist`);
    fs.writeFileSync(
      OUTPUT_FILE,
      `// This file is auto-generated by scripts/generate-blog-index.mjs
// Do not edit manually. Run "npm run content:gen" to regenerate.

export type BlogIndexItem = {
  slug: string;
  title: string;
  description: string;
  date: string;
  tags: string[];
  intent?: string;
  cover?: string;
  readingMinutes: number;
};

export const blogIndex: BlogIndexItem[] = [];
`,
      "utf8"
    );
    return;
  }

  const files = fs.readdirSync(BLOG_DIR).filter((f) => f.endsWith(".mdx") || f.endsWith(".md"));
  const items = [];

  for (const file of files) {
    const slug = file.replace(/\.mdx?$/, "");
    const filePath = path.join(BLOG_DIR, file);
    const raw = fs.readFileSync(filePath, "utf8");
    
    try {
      const { data, content } = matter(raw);

      // Проверяем обязательные поля
      if (!data.title) {
        console.warn(`Warning: ${file} missing required field "title"`);
        continue;
      }
      if (!data.description) {
        console.warn(`Warning: ${file} missing required field "description"`);
        continue;
      }
      if (!data.date) {
        console.warn(`Warning: ${file} missing required field "date"`);
        continue;
      }

      // Вычисляем reading time
      const stats = readingTime(content);
      const readingMinutes = Math.max(1, Math.round(stats.minutes));

      // Нормализуем дату: если это Date объект, преобразуем в ISO строку, иначе используем как есть
      let dateStr = String(data.date);
      if (data.date instanceof Date) {
        dateStr = data.date.toISOString().split("T")[0];
      } else if (typeof data.date === "string" && data.date.includes("T")) {
        // Если строка содержит время, берем только дату
        dateStr = data.date.split("T")[0];
      }

      const item = {
        slug,
        title: String(data.title),
        description: String(data.description),
        date: dateStr,
        tags: Array.isArray(data.tags) ? data.tags.map(String) : [],
        intent: data.intent ? String(data.intent) : undefined,
        cover: data.cover ? String(data.cover) : undefined,
        readingMinutes,
      };

      items.push(item);
    } catch (error) {
      console.error(`Error processing ${file}:`, error.message);
      continue;
    }
  }

  // Сортируем по дате (desc)
  items.sort((a, b) => {
    const dateA = new Date(a.date);
    const dateB = new Date(b.date);
    return dateB - dateA;
  });

  // Генерируем TypeScript файл
  const typeDefinition = `export type BlogIndexItem = {
  slug: string;
  title: string;
  description: string;
  date: string;
  tags: string[];
  intent?: string;
  cover?: string;
  readingMinutes: number;
};`;

  const indexExport = `export const blogIndex: BlogIndexItem[] = ${JSON.stringify(items, null, 2)};`;

  const output = `// This file is auto-generated by scripts/generate-blog-index.mjs
// Do not edit manually. Run "npm run content:gen" to regenerate.

${typeDefinition}

${indexExport}
`;

  // Создаём директорию lib если её нет
  const libDir = path.dirname(OUTPUT_FILE);
  if (!fs.existsSync(libDir)) {
    fs.mkdirSync(libDir, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_FILE, output, "utf8");
  console.log(`✓ Generated ${items.length} blog posts in ${OUTPUT_FILE}`);
}

generateBlogIndex();
